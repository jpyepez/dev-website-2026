import { describe, expect, test } from "bun:test";
import { decide, parseArgs, USAGE } from "./triage-outcome";

const owner = "jpyepez";
const disclaimer = "> *This was generated by AI during triage.*";
const reasons = `${disclaimer}\n\n**Outcome: \`ready\`** (category: \`bug\`)\n\nIt meets the bar.`;

describe("decide", () => {
  test("fails a re-triage that left the earlier labels and posted nothing new", () => {
    expect(
      decide({
        labels: ["bug", "ready"],
        comments: [{ id: 100, author: owner, body: reasons }],
        since: 100,
        owner,
      }),
    ).toEqual({ pass: false, reason: "no new triage comment since comment 100" });
  });

  test("passes a run that posted a triage comment and left one category and one outcome", () => {
    expect(
      decide({
        labels: ["enhancement", "needs-info"],
        comments: [
          { id: 100, author: owner, body: "Some earlier note." },
          { id: 105, author: owner, body: reasons },
        ],
        since: 100,
        owner,
      }),
    ).toEqual({ pass: true, outcome: "needs-info" });
  });

  test("passes a re-triage that lands on the same outcome as before, with a new triage comment", () => {
    expect(
      decide({
        labels: ["bug", "ready"],
        comments: [
          { id: 100, author: owner, body: reasons },
          { id: 120, author: owner, body: reasons },
        ],
        since: 100,
        owner,
      }),
    ).toEqual({ pass: true, outcome: "ready" });
  });

  test("passes a new issue with no comments before the run and one triage comment", () => {
    expect(
      decide({ labels: ["documentation", "wontfix"], comments: [{ id: 7, author: owner, body: reasons }], since: 0, owner }),
    ).toEqual({ pass: true, outcome: "wontfix" });
  });

  test("ignores triage comments from earlier runs", () => {
    expect(
      decide({
        labels: ["bug", "ready"],
        comments: [
          { id: 90, author: owner, body: reasons },
          { id: 100, author: owner, body: reasons },
        ],
        since: 100,
        owner,
      }),
    ).toEqual({ pass: false, reason: "no new triage comment since comment 100" });
  });

  test("ignores a new owner comment that doesn't start with the disclaimer", () => {
    expect(
      decide({
        labels: ["bug", "ready"],
        comments: [{ id: 105, author: owner, body: "Looks ready to me." }],
        since: 100,
        owner,
      }),
    ).toEqual({ pass: false, reason: "no new triage comment since comment 100" });
  });

  test("fails when the only new comment is the Original note", () => {
    expect(
      decide({
        labels: ["bug", "ready"],
        comments: [{ id: 105, author: owner, body: `${disclaimer}\n\nOriginal note:\n\nThe nav breaks at 390.` }],
        since: 100,
        owner,
      }),
    ).toEqual({ pass: false, reason: "no new triage comment since comment 100" });
  });

  test("ignores a disclaimer comment posted by someone other than the owner", () => {
    expect(
      decide({
        labels: ["bug", "ready"],
        comments: [{ id: 105, author: "someone-else", body: reasons }],
        since: 100,
        owner,
      }),
    ).toEqual({ pass: false, reason: "no new triage comment since comment 100" });
  });

  test.each([
    [["bug", "enhancement", "ready"], "needs one category and one outcome label, has: bug, enhancement, ready"],
    [["bug", "ready", "wontfix"], "needs one category and one outcome label, has: bug, ready, wontfix"],
    [["bug", "needs-triage"], "needs one category and one outcome label, has: bug, needs-triage"],
    [["ready"], "needs one category and one outcome label, has: ready"],
    [[], "needs one category and one outcome label, has: none"],
  ])("fails labels %p with the label reason, even with a new triage comment", (labels, reason) => {
    expect(
      decide({ labels, comments: [{ id: 105, author: owner, body: reasons }], since: 100, owner }),
    ).toEqual({ pass: false, reason });
  });
});

describe("parseArgs", () => {
  test("reads the issue number and the marker comment id", () => {
    expect(parseArgs(["58", "6573492524"])).toEqual({ issue: 58, since: 6573492524 });
    expect(parseArgs(["58", "0"])).toEqual({ issue: 58, since: 0 });
  });

  test.each([[[]], [["58"]], [["abc", "0"]], [["0", "0"]], [["58", "x"]], [["58", "-1"]], [["58", "1.5"]], [["58", "0", "extra"]]])(
    "rejects %p with the usage message",
    (args) => {
      expect(() => parseArgs(args)).toThrow(USAGE);
    },
  );
});
