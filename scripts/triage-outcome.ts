/// <reference types="bun" />
// The outcome check after the Triage agent (.github/workflows/triage.yml). A run passes
// only if the issue has one category and one outcome label and this run's agent posted
// its triage reasons comment. Labels alone can't show that: on a re-triage the earlier
// run's labels already pass. On a pass it sets the board Status; on a fail it prints a
// GitHub ::error:: line, exits non-zero and leaves the Status alone.
//
//   bun run triage-outcome <issue-number> <since-comment-id>     e.g. bun run triage-outcome 58 6573492524
//
// <since-comment-id> is the issue's newest comment id before the agent ran, or 0 if it
// had none. Comment ids increase over time, so any id above it was posted during the run.

import { gh, setStatus } from "./board-status";

const OWNER = "jpyepez";
const REPO = "jpyepez/dev-website-2026";

export const USAGE = "Usage: bun run triage-outcome <issue-number> <since-comment-id>  (e.g. 58 0)";
export const DISCLAIMER = "> *This was generated by AI during triage.*";

const CATEGORIES = ["bug", "enhancement", "documentation"];
const OUTCOMES = ["ready", "needs-info", "ready-for-human", "wontfix", "needs-triage"];

export type Comment = { id: number; author: string; body: string };
export type Decision = { pass: true; outcome: string } | { pass: false; reason: string };

export function parseArgs(args: string[]): { issue: number; since: number } {
  const [issue = "", since = "", ...rest] = args;
  if (!/^[1-9]\d*$/.test(issue) || !/^\d+$/.test(since) || rest.length > 0) throw new Error(USAGE);
  return { issue: Number(issue), since: Number(since) };
}

// The rules, in order; the first that fails is the reason given.
export function decide({
  labels,
  comments,
  since,
  owner,
}: {
  labels: string[];
  comments: Comment[];
  since: number;
  owner: string;
}): Decision {
  const categories = labels.filter((l) => CATEGORIES.includes(l));
  const outcomes = labels.filter((l) => OUTCOMES.includes(l));
  if (categories.length !== 1 || outcomes.length !== 1 || outcomes[0] === "needs-triage") {
    return { pass: false, reason: `needs one category and one outcome label, has: ${labels.join(", ") || "none"}` };
  }

  // The bot posts with the owner's PAT, so its comments are the owner's. The Original
  // note a `ready` triage posts also starts with the disclaimer, but it isn't the reasons.
  const newer = comments.filter((c) => c.id > since);
  const triaged = newer.some((c) => {
    const body = c.body.trimStart();
    return (
      c.author === owner &&
      body.startsWith(DISCLAIMER) &&
      !body.slice(DISCLAIMER.length).trimStart().startsWith("Original note:")
    );
  });
  if (!triaged) {
    const found = `${newer.length} newer comment${newer.length === 1 ? "" : "s"}, none a triage comment`;
    return { pass: false, reason: `no new triage comment since comment ${since} (${found})` };
  }

  return { pass: true, outcome: outcomes[0] };
}

// The board column a passing triage moves the issue to, or null to leave it alone.
export function statusFor(outcome: string, assigned: boolean): string | null {
  // HITL is everything waiting on the owner.
  if (outcome !== "ready") return "HITL";
  // Someone may already have claimed it and moved it to In progress.
  return assigned ? null : "Ready";
}

if (import.meta.main) {
  let issue = 0;
  try {
    const args = parseArgs(process.argv.slice(2));
    issue = args.issue;
    const { labels, assignees } = JSON.parse(
      gh(["issue", "view", String(issue), "--repo", REPO, "--json", "labels,assignees"]),
    ) as { labels: { name: string }[]; assignees: unknown[] };
    // REST, not `gh issue view`: it gives the numeric ids the marker is compared with.
    // --slurp gathers every page into one array of pages.
    const pages = JSON.parse(
      gh(["api", "--paginate", "--slurp", `repos/${REPO}/issues/${issue}/comments?per_page=100`]),
    ) as { id: number; user: { login: string } | null; body: string | null }[][];
    const comments = pages.flat().map((c) => ({ id: c.id, author: c.user?.login ?? "", body: c.body ?? "" }));

    const decision = decide({ labels: labels.map((l) => l.name), comments, since: args.since, owner: OWNER });
    if (!decision.pass) {
      console.log(`::error::#${issue} failed the triage outcome check: ${decision.reason}. Re-dispatch Triage.`);
      process.exit(1);
    }
    console.log(`#${issue} triaged: ${decision.outcome}`);
    const column = statusFor(decision.outcome, assignees.length > 0);
    if (column) console.log(`#${issue} → ${setStatus(issue, column)}`);
    else console.log(`#${issue} is assigned, Status left alone`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.log(`::error::${issue ? `#${issue}: ` : ""}${message.split("\n")[0]}`);
    console.error(message);
    process.exit(1);
  }
}
